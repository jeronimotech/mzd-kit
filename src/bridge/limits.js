// Abuse and cost protection for a bridge exposed to the internet.

/** Fixed-window counter: allow(key) is true while `key` stays under `max` per `windowMs`. */
export function createRateLimiter({ max, windowMs, maxKeys = 50000 }) {
  const hits = new Map(); // key -> { start, count }
  return {
    allow(key, now = Date.now()) {
      let h = hits.get(key);
      if (!h || now - h.start >= windowMs) {
        h = { start: now, count: 0 };
        hits.delete(key);
        hits.set(key, h);
        if (hits.size > maxKeys) hits.delete(hits.keys().next().value);
      }
      if (h.count >= max) return false;
      h.count++;
      return true;
    },
  };
}

/** Global daily budget (UTC day) for paid upstream calls. */
export function createDailyBudget(limit) {
  let day = '';
  let used = 0;
  return {
    take(now = new Date()) {
      const d = now.toISOString().slice(0, 10);
      if (d !== day) { day = d; used = 0; }
      if (limit > 0 && used >= limit) return false;
      used++;
      return true;
    },
    get used() { return used; },
  };
}

/** Per-device instances with an LRU cap, so one public bridge serves many phones privately. */
export function createDeviceMap(factory, maxDevices = 2000) {
  const map = new Map();
  return {
    get(device) {
      let v = map.get(device);
      if (v) {
        map.delete(device);
      } else {
        v = factory(device);
        if (map.size >= maxDevices) map.delete(map.keys().next().value);
      }
      map.set(device, v);
      return v;
    },
    get size() { return map.size; },
  };
}

/** A device id is an opaque random id generated by the app (8–64 chars). */
export function validDevice(id) {
  return typeof id === 'string' && /^[A-Za-z0-9_-]{8,64}$/.test(id);
}

/** Client IP, honoring the proxy header set by the hosting platform. */
export function clientIp(req) {
  const fwd = req.headers['x-forwarded-for'];
  if (typeof fwd === 'string' && fwd) return fwd.split(',')[0].trim();
  return req.socket?.remoteAddress || 'unknown';
}
